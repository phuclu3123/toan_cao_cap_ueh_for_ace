import { readFile, writeFile, rename } from 'node:fs/promises';
import { practiceExams } from '../src/data/practiceExams.js';
// Generated from the same questions and timer settings used by the real exam screen.
const catalog = practiceExams.map(({ id, title, durationMinutes, questions, sourcePdf }) => ({ id, title, durationMinutes, questionsCount: questions.length, sourcePdf }));
const target = new URL('../src/data/practiceCatalog.js', import.meta.url);
const source = `// Generated by scripts/export-practice-catalog.mjs. Do not hand-edit counts.\nexport const practiceCatalog = ${JSON.stringify(catalog, null, 2)};\n`;
if (await readFile(target, 'utf8').catch(() => '') !== source) {
  const temporary = new URL('../src/data/practiceCatalog.js.tmp', import.meta.url);
  await writeFile(temporary, source);
  await rename(temporary, target);
}
console.log(`Exported ${catalog.length} real exam summaries.`);
