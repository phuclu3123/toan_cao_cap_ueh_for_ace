"""Render verified exam pages from the original local publications."""
import hashlib
import json
import re
from pathlib import Path
import pymupdf
from PIL import Image

frontend = Path(__file__).resolve().parents[1]
output = frontend / 'public/images/exams'
output.mkdir(parents=True, exist_ok=True)
k51 = 'K51_2_dot.pdf'
final = 'DE_THI_CHINH/FINAL_2807_1.pdf'
pages = [
    ('k51-tonghop', k51, 20), ('k51-204', k51, 5), ('k51-118', k51, 8),
    ('k51-354', k51, 11), ('k51-442', k51, 14), ('k50-dot-2', final, 22),
    ('ap1-f2', final, 18), ('ap1-f1', final, 20), ('ap1-f3', final, 13),
    ('ap1-f4', final, 15), ('ap1-f6', final, 9), ('ap1-f7', final, 7)
]
metadata = {}
def save(page, clip, name):
    pixels = page.get_pixmap(matrix=pymupdf.Matrix(2, 2), clip=clip, alpha=False)
    image = Image.frombytes('RGB', (pixels.width, pixels.height), pixels.samples)
    image.thumbnail((1100, 1450), Image.Resampling.LANCZOS)
    target = output / name
    temporary = target.with_suffix('.tmp')
    image.save(temporary, 'WEBP', quality=90, method=6)
    temporary.replace(target)
    return image.size

for identifier, source, number in pages:
    path = frontend / 'public/docs' / source
    with pymupdf.open(path) as document:
        page = document[number - 1]
        blocks = page.get_text('blocks')
        second = next((block[1] for block in blocks if re.search(r'Câu\s*2[.:]', block[4])), 420)
        clip = pymupdf.Rect(40, 45, page.rect.width - 40, max(250, second - 9))
        size = save(page, clip, identifier + '.webp')
        entry = {'image': '/images/exams/' + identifier + '.webp', 'width': size[0], 'height': size[1], 'pdf': '/docs/' + source, 'page': number, 'crop': list(clip), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
        if identifier in ['k51-tonghop', 'k51-204', 'k51-118']:
            save(page, page.rect, identifier + '-page.webp')
            entry['fullPageImage'] = '/images/exams/' + identifier + '-page.webp'
        metadata[identifier] = entry

(output / 'sources.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
module = frontend / 'src/data/examPreviewData.js'
temporary = module.with_suffix('.tmp')
temporary.write_text('// Generated by render-exam-preview-assets.py from verified original PDF pages.\nexport const examPreviewData = ' + json.dumps(metadata, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
temporary.replace(module)
print(json.dumps({'previews': len(metadata), 'bytes': sum(file.stat().st_size for file in output.glob('*.webp'))}))
